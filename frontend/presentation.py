PRIORITY_LABELS = {
    'structure': 'Положение в сети',
    'seed_proximity': 'Близость к исходным клиентам',
    'magnitude': 'Масштаб переводов',
    'role_support': 'Поддержка роли',
}


def priority_parts(row):
    return [(label, float(row[f'contribution_{key}']) * 100)
            for key, label in PRIORITY_LABELS.items()]


def priority_explanation(row):
    parts = sorted(priority_parts(row), key=lambda part: -part[1])
    if not any(value > 0 for _, value in parts):
        return 'Все четыре вклада в приоритет равны нулю: доступные признаки не поднимают клиента в очереди.'
    return 'Главные вклады: ' + '; '.join(f'{label.lower()} — {value:.1f} балла' for label, value in parts[:2]) + '.'
